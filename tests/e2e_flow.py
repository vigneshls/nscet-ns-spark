import sys, re
from playwright.sync_api import sync_playwright, expect
BASE="http://localhost:4173/nscet-ns-spark/"
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg=b.new_page(viewport={"width":1366,"height":900})
    pg.on("console", lambda m: m.type=="error" and errs.append(m.text))
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(BASE)
    pg.get_by_role("button", name=re.compile("^HoD – MECH")).click()
    expect(pg.get_by_role("heading", name=re.compile("Mechanical Engineering"))).to_be_visible()
    pg.screenshot(path="/home/claude/e2e/1-hod-dashboard.png", full_page=True)
    # create proposal
    pg.get_by_role("link", name="+ New project").first.click()
    pg.fill("#title","Automated paddle alignment jig")
    pg.fill("#desc","A jig that aligns flume paddles automatically using laser sensors and stepper motors.")
    pg.fill("#prob","Manual paddle alignment takes two days.")
    pg.fill("#sol","Laser-guided stepper alignment with a PLC.")
    pg.fill("#tech","Arduino, Stepper motors, Laser sensors")
    sels=pg.get_by_label("Person")
    sels.nth(0).select_option(label="Faculty MECH-4 (MECH)")
    pg.get_by_role("button", name="+ Student").click()
    pg.get_by_label("Person").nth(1).select_option(label="Student MECH-5 (MECH)")
    pg.get_by_role("button", name="Submit to NS Spark").click()
    expect(pg.get_by_text("NSS-MECH-2026-002").first).to_be_visible()
    pg.screenshot(path="/home/claude/e2e/2-new-project.png", full_page=True)
    # switch to admin
    pg.get_by_role("button", name="Sign out").click()
    pg.get_by_role("button", name=re.compile("^NS Spark Coordinator")).click()
    pg.get_by_role("link", name="Proposals").click()
    card=pg.locator(".card", has_text="Automated paddle alignment jig")
    card.get_by_role("button", name="Approve").click()
    pg.get_by_role("button", name="Confirm").click()
    expect(pg.get_by_text(re.compile("approved and is now active"))).to_be_visible()
    pg.get_by_role("link", name="Dashboard").click()
    pg.wait_for_timeout(500)
    pg.screenshot(path="/home/claude/e2e/3-admin-dashboard.png", full_page=True)
    # student logs time
    pg.get_by_role("button", name="Sign out").click()
    pg.get_by_label("Any demo user").select_option(label="Student MECH-5 — Student")
    pg.get_by_role("button", name="Go").click()
    pg.get_by_role("link", name="My Timesheet").click()
    pg.get_by_label("Project").select_option(index=0)
    pg.fill("#lh","3")
    pg.fill("#lw","Mounted laser sensors on the jig frame")
    pg.get_by_role("button", name="Submit entry").click()
    expect(pg.get_by_text(re.compile("Logged 3 h"))).to_be_visible()
    # faculty approves
    pg.get_by_role("button", name="Sign out").click()
    pg.get_by_label("Any demo user").select_option(label="Faculty MECH-4 — Faculty")
    pg.get_by_role("button", name="Go").click()
    pg.get_by_role("link", name="Approvals").click()
    pg.locator(".card", has_text="Automated paddle").get_by_role("button", name="Select project").click()
    pg.get_by_role("button", name="Approve", exact=True).click()
    expect(pg.get_by_text(re.compile(r"entr(y|ies) approved"))).to_be_visible()
    # principal report
    pg.get_by_role("button", name="Sign out").click()
    pg.get_by_role("button", name=re.compile("^Principal, NSCET")).click()
    pg.get_by_role("link", name="Reports").click()
    expect(pg.get_by_text("Department summary")).to_be_visible()
    pg.screenshot(path="/home/claude/e2e/4-daily-report.png", full_page=True)
    pg.get_by_role("tab", name="Monthly report").click()
    pg.screenshot(path="/home/claude/e2e/5-monthly.png", full_page=True)
    # project detail timesheet matrix (admin)
    pg.get_by_role("button", name="Sign out").click()
    pg.get_by_role("button", name=re.compile("^NS Spark Coordinator")).click()
    pg.get_by_role("link", name="Projects").click()
    pg.get_by_text("Wave Flume Wave-Generator").first.click()
    pg.get_by_role("tab", name=re.compile("Tasks")).click()
    pg.screenshot(path="/home/claude/e2e/6-tasks.png", full_page=True)
    pg.get_by_role("tab", name=re.compile("Timesheet")).click()
    pg.wait_for_timeout(300)
    pg.screenshot(path="/home/claude/e2e/7-matrix.png", full_page=True)
    # mobile
    m=b.new_page(viewport={"width":375,"height":800})
    m.on("pageerror", lambda e: errs.append(str(e)))
    m.goto(BASE); m.get_by_role("button", name=re.compile("^HoD – AIDS")).click()
    m.wait_for_timeout(500)
    m.screenshot(path="/home/claude/e2e/8-mobile.png", full_page=True)
    sw=m.evaluate("document.documentElement.scrollWidth")
    print("mobile scrollWidth", sw)
    b.close()
